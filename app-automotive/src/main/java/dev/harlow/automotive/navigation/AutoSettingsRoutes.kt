/** Settings for AAOS. No in-app updates: the OEM's store delivers them. */
@Composable
internal fun AutoSettingsRoute(
    mainViewModel: MainViewModel,
    appVersion: String,
    serverUrl: String?,
    onBack: () -> Unit,
    onLicensesClick: () -> Unit,
) {
    val connectionState by mainViewModel.connectionState.collectAsStateWithLifecycle()
    val lastSyncTimestamp by mainViewModel.lastSyncTimestamp.collectAsStateWithLifecycle()
    val isSyncing by mainViewModel.isSyncing.collectAsStateWithLifecycle()
    val syncProgress by mainViewModel.syncProgress.collectAsStateWithLifecycle()
    val isCleaningUp by mainViewModel.isCleaningUp.collectAsStateWithLifecycle()
    val isForceOffline by mainViewModel.isForceOffline.collectAsStateWithLifecycle()
    val autoSyncIntervalHours by mainViewModel.autoSyncIntervalHours.collectAsStateWithLifecycle()
    val streamQuality by mainViewModel.streamQuality.collectAsStateWithLifecycle()
    val autoResume by mainViewModel.autoResume.collectAsStateWithLifecycle()
    val listView by mainViewModel.listView.collectAsStateWithLifecycle()

    SettingsScreen(
        appVersion = appVersion,
        serverUrl = serverUrl ?: "",
        connectionState = connectionState,
        lastSyncTimestamp = lastSyncTimestamp,
        isSyncing = isSyncing,
        syncProgress = syncProgress,
        isCleaningUp = isCleaningUp,
        isForceOffline = isForceOffline,
        autoSyncIntervalHours = autoSyncIntervalHours,
        streamQuality = streamQuality,
        autoResume = autoResume,
        listView = listView,
        onBack = onBack,
        onSyncNow = mainViewModel::syncNow,
        onCleanup = mainViewModel::cleanupLibrary,
        onForceOfflineChange = mainViewModel::setForceOffline,
        onAutoSyncIntervalChange = mainViewModel::setAutoSyncInterval,
        onStreamQualityChange = mainViewModel::setStreamQuality,
        onAutoResumeChange = mainViewModel::setAutoResume,
        onListViewChange = mainViewModel::setListView,
        onLicensesClick = onLicensesClick,
        onLogout = mainViewModel::logout,
    )
}

/** Open-source licenses — generated by the AboutLibraries plugin, plus Harlow and what the plugin can't see. */
@Composable
internal fun AutoLicensesRoute(onBack: () -> Unit) {
    val context = LocalContext.current
    val (community, platform) = remember {
        val readAsset = { name: String ->
            context.assets.open("licenses/$name").bufferedReader().use { it.readText() }
        }
        val generated = Libs.Builder().withContext(context).build().libraries
        val all = manualLibraries(readAsset) + generated.map { it.withBundledLicenseTexts(readAsset) }
        all.partition { library ->
            val group = library.uniqueId.substringBefore(":")
            PLATFORM_PREFIXES.none { group.startsWith(it) }
        }
    }
    LicensesScreen(
        communityLibraries = community,
        platformLibraries = platform,
        onBack = onBack,
    )
}

private val PLATFORM_PREFIXES = listOf(
    "androidx.", "com.google.", "jakarta.", "javax.",
    "org.jetbrains.", "org.jspecify",
)
